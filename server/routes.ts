import route3 from "./api/connections/meituan/remote/frame.get";
import route4 from "./api/connections/meituan/remote/input.post";
import route5 from "./api/connections/meituan/remote/verify.post";
import route6 from "./api/connections/meituan/start.post";
import route7 from "./api/connections/meituan/verify.post";
import route8 from "./api/connections/meituan.delete";
import route9 from "./api/connections/waimai/profile.post";
import route10 from "./api/connections/waimai/wechat.post";
import route11 from "./api/connections/waimai.delete";
import route12 from "./api/connections/xiaochan/profile.post";
import route13 from "./api/connections/xiaochan/wechat.post";
import route14 from "./api/connections/xiaochan.delete";
import route15 from "./api/dashboard.get";
