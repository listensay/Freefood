import route30 from "./api/xiaochan/schedule.post";

export function apiRouter() {
  const router = createRouter();
  router.delete("/api/connections/:provider", loggedHandler(route0));
  router.post("/api/connections/meituan/browser", loggedHandler(route1));
  router.post("/api/connections/meituan/remote/end", loggedHandler(route2));
  router.get("/api/connections/meituan/remote/frame", route3);
  router.post("/api/connections/meituan/remote/input", loggedHandler(route4));
  router.post("/api/connections/meituan/remote/verify", loggedHandler(route5));
  router.post("/api/connections/meituan/start", loggedHandler(route6));
  router.post("/api/connections/meituan/verify", loggedHandler(route7));
  router.delete("/api/connections/meituan", loggedHandler(route8));
  router.post("/api/connections/waimai/profile", loggedHandler(route9));
  router.post("/api/connections/waimai/wechat", loggedHandler(route10));
  router.delete("/api/connections/waimai", loggedHandler(route11));
  router.post("/api/connections/xiaochan/profile", loggedHandler(route12));
  router.post("/api/connections/xiaochan/wechat", loggedHandler(route13));
  router.delete("/api/connections/xiaochan", loggedHandler(route14));
  router.get("/api/dashboard", route15);
  router.post("/api/import", loggedHandler(route19));
  router.post("/api/location", loggedHandler(route20));
  router.post("/api/sync", loggedHandler(route21));
  router.post("/api/waimai/cancel", loggedHandler(route22));
  router.post("/api/waimai/enroll", loggedHandler(route23));
  router.delete("/api/waimai/schedule", loggedHandler(route24));
  router.post("/api/waimai/schedule", loggedHandler(route25));
  router.post("/api/xiaochan/cancel", loggedHandler(route26));
  router.post("/api/xiaochan/enroll", loggedHandler(route27));
  router.post("/api/xiaochan/schedule-options", loggedHandler(route28));
  router.delete("/api/xiaochan/schedule", loggedHandler(route29));
  router.post("/api/xiaochan/schedule", loggedHandler(route30));
  router.post("/api/logs/query", logQuery);
  router.get("/api/logs/export", logExport);
  router.delete("/api/logs", logClear);
  return router;
}
